export function encontrarTeatroPorNome(nome) {
  if (!nome) return null;
  const normalizar = (s) => s.trim().toLowerCase();
  const nomeNorm = normalizar(nome);
  return (
    teatros.find(
      (t) =>
        normalizar(t.nomeOficial) === nomeNorm ||
        t.aliases.some((a) => a && normalizar(a) === nomeNorm)
    ) || null
  );
}